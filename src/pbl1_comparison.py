"""PBL-1 comparative analysis: simple baselines next to the fitted models.

Usage: python src/pbl1_comparison.py   (after extended_models.py and phase2_evaluation.py)
Writes ONLY pbl-1/04_comparative_analysis/comparison_numbers.md and figures/C*.png.
Same data, splits and seed as the Phase 1 models. The pharmacy keyword rule takes its words
from the TRAINING split (top-5 log-odds words), never from test.
"""
import json
import sys
import warnings
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import linear_regression_mle as lr  # noqa: E402
import logistic_regression_classification as L  # noqa: E402
from matching.features import title_tokens  # noqa: E402

OUT = Path("pbl-1/04_comparative_analysis")
FIG = OUT / "figures"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
INK2, MUTED, GRID, SURFACE, LIGHT = "#52514e", "#898781", "#e1e0d9", "#fcfcfb", "#c9c8c1"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": MUTED, "axes.labelcolor": INK2, "xtick.color": MUTED, "ytick.color": MUTED,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.spines.top": False,
    "axes.spines.right": False, "font.size": 10, "axes.titlesize": 11,
    "axes.titleweight": "bold", "legend.frameon": False,
})


def reg_metrics(y, p):
    rss = float(np.sum((y - p) ** 2))
    return {"RMSE": float(np.sqrt(rss / len(y))), "MAE": float(np.mean(np.abs(y - p))),
            "R2": float(1 - rss / np.sum((y - y.mean()) ** 2))}


def ols(cols, train, test):
    Xtr = np.column_stack([np.ones(len(train))] + [train[c].astype(float) for c in cols])
    Xte = np.column_stack([np.ones(len(test))] + [test[c].astype(float) for c in cols])
    beta = np.linalg.lstsq(Xtr, train.y.to_numpy(), rcond=None)[0]
    return Xtr @ beta, Xte @ beta


def hbar(ax, names, values, highlight, fmt):
    ax.barh(names, values, color=[BLUE if h else LIGHT for h in highlight], height=0.6)
    for i, x in enumerate(values):
        ax.text(x + 0.01 * max(values), i, fmt.format(x), va="center", fontsize=8, color=INK2)
    ax.grid(axis="y", visible=False)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    FIG.mkdir(parents=True, exist_ok=True)
    md = ["# Comparison numbers (generated by `python src/pbl1_comparison.py`; do not edit)", ""]

    # ---------------------------------------------------------------- regression
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        ann = lr.load_annotations()
    ann["y"] = ann[lr.TARGET].astype(float)
    train, test = lr.split_by_requirement(ann)
    rows = []
    mean_tr = np.full(len(train), train.y.mean())
    mean_te = np.full(len(test), train.y.mean())
    rows.append(("Baseline: predict the train mean", reg_metrics(train.y, mean_tr),
                 reg_metrics(test.y, mean_te)))
    for name, cols in [("OLS: category_match only", ["category_match"]),
                       ("OLS: category_match + within_radius",
                        ["category_match", "within_radius"]),
                       ("OLS: all 6 features (Phase 1)", lr.FEATURES)]:
        ptr, pte = ols(cols, train, test)
        rows.append((name, reg_metrics(train.y, ptr), reg_metrics(test.y, pte)))
    ext = json.loads(Path("reports/extended_models_metrics.json").read_text(encoding="utf-8"))
    for name, m in ext["regression"]["metrics"].items():
        if name.startswith("OLS"):
            continue
        rows.append((name, {"R2": m["train"]["R2"], "RMSE": m["train"]["RMSE"],
                            "MAE": m["train"]["MAE"]},
                     {"R2": m["test"]["R2"], "RMSE": m["test"]["RMSE"], "MAE": m["test"]["MAE"]}))
    reg = pd.DataFrame([{"model": n, "train R²": a["R2"], "test R²": b["R2"],
                         "test RMSE": b["RMSE"], "test MAE": b["MAE"],
                         "gap R² (train − test)": a["R2"] - b["R2"]} for n, a, b in rows])
    md += ["## A. Regression: expected_score on the 6 held-out requirements (90 pairs)", "",
           md_table(reg.round(4)), "",
           f"- Test sd of the target: {test.y.std(ddof=0):.4f}; predicting the train mean "
           f"({train.y.mean():.4f}) gives test RMSE {rows[0][2]['RMSE']:.4f}.", ""]

    fig, ax = plt.subplots(figsize=(8, 4.8))
    r = reg.iloc[::-1]
    hbar(ax, r.model, r["test RMSE"], [not m.startswith("Baseline") for m in r.model], "{:.2f}")
    ax.set(xlabel="test RMSE (score points, lower is better)",
           title="C01 Regression: baselines vs models (test set)")
    fig.tight_layout()
    fig.savefig(FIG / "C01_regression_vs_baselines.png", dpi=150)
    plt.close(fig)

    # ---------------------------------------------------------------- classification
    v = L.load_vendors()
    vtr, vte = L.split(v)
    pos, neg = vtr[vtr.y == 1], vtr[vtr.y == 0]
    dfp = Counter(t for x in pos.title for t in title_tokens(x))
    dfn = Counter(t for x in neg.title for t in title_tokens(x))
    lo = {t: np.log((dfp[t] + 0.5) / (len(pos) + 1)) - np.log((dfn[t] + 0.5) / (len(neg) + 1))
          for t in set(dfp) | set(dfn) if dfp[t] + dfn[t] >= 10}
    rule_words = sorted(lo, key=lambda t: -lo[t])[:5]
    rule_pred = vte.title.map(lambda x: bool(title_tokens(x) & set(rule_words))).astype(float)
    rule = L.evaluate(vte.y.to_numpy(), rule_pred.to_numpy())
    clf_rows = [("Baseline: always 'not pharmacy'", {
        "accuracy": float((vte.y == 0).mean()), "precision": 0.0, "recall": 0.0, "f1": 0.0,
        "roc_auc": 0.5})]
    clf_rows.append((f"Baseline: title has one of {rule_words} (rule from train)", rule))
    for name, m in ext["classification"]["metrics"].items():
        clf_rows.append((name, m))
    clf = pd.DataFrame([{"model": n, "accuracy": m["accuracy"], "precision": m["precision"],
                         "recall": m["recall"], "F1": m["f1"], "ROC-AUC": m["roc_auc"]}
                        for n, m in clf_rows])
    md += ["## B. Classification: is_pharmacy on the test split (923 vendors, 97 positive)", "",
           md_table(clf.round(4)), "",
           f"- The rule's ROC-AUC is computed from a 0/1 score, so it is a single point, not "
           f"a ranking. Rule confusion matrix: {rule['confusion_matrix']}.", ""]

    fig, ax = plt.subplots(figsize=(8, 4.8))
    c = clf.iloc[::-1]
    hbar(ax, [n if len(n) < 45 else "Rule: title has a train pharmacy word" for n in c.model],
         c.F1, [not m.startswith("Baseline") for m in c.model], "{:.3f}")
    ax.set(xlabel="test F1 (higher is better)",
           title="C02 Classification: baselines vs models (test split)")
    fig.tight_layout()
    fig.savefig(FIG / "C02_classification_vs_baselines.png", dpi=150)
    plt.close(fig)

    # ---------------------------------------------------------------- ranking (Phase 2)
    p2 = Path("reports/phase2_metrics.json")
    if p2.exists():
        m2 = json.loads(p2.read_text(encoding="utf-8"))
        rk = pd.DataFrame([{"ranking": k, "NDCG@5": d["mean_ndcg@5"],
                            "precision@5": d["mean_precision@5"]}
                           for k, d in m2["summary"].items()])
        md += ["## C. Ranking: 6 held-out requirements × 15 judged vendors (Phase 2)", "",
               md_table(rk.round(4)), "",
               f"- Random averaged over 1000 permutations: NDCG@5 "
               f"{m2['random_mean_ndcg@5_over_1000_permutations']:.4f}.", ""]

    (OUT / "comparison_numbers.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


def md_table(df):
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
