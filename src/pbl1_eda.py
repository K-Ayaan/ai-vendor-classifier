"""PBL-1 exploratory data analysis: figures and numbers for pbl-1/02_eda_insights/.

Usage: python src/pbl1_eda.py
Reads data/processed/ and data/annotation/ (read-only) and writes ONLY to
pbl-1/02_eda_insights/figures/E*.png and pbl-1/02_eda_insights/eda_numbers.md.
Anything that involves a target (expected_score, is_pharmacy) is computed on the TRAINING
split only (same splits and seed as the models), so the EDA does not peek at test data.
"""
import sys
import warnings
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.spatial import cKDTree  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import linear_regression_mle as lr  # noqa: E402
import logistic_regression_classification as L  # noqa: E402
from matching.features import FEATURES, category_set, title_tokens  # noqa: E402

OUT = Path("pbl-1/02_eda_insights")
FIG = OUT / "figures"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
INK, INK2, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#fcfcfb"
LIGHT = "#c9c8c1"
KM_PER_DEG_LAT = 111.32

plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": MUTED, "axes.labelcolor": INK2, "xtick.color": MUTED, "ytick.color": MUTED,
    "text.color": INK, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
    "axes.spines.top": False, "axes.spines.right": False, "font.size": 10,
    "axes.titlesize": 11, "axes.titleweight": "bold", "legend.frameon": False,
})


def save(fig, name):
    fig.tight_layout()
    fig.savefig(FIG / f"{name}.png", dpi=150)
    plt.close(fig)


def md_table(df):
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    FIG.mkdir(parents=True, exist_ok=True)
    v = L.load_vendors()
    v["cats"] = v.categories.map(category_set)
    reqs = pd.read_csv("data/processed/requirements.csv", keep_default_na=False)
    md = ["# EDA numbers (generated by `python src/pbl1_eda.py`; do not edit by hand)", "",
          "Target-related numbers use the training split only (24 train requirements for "
          "expected_score; 3,689 train vendors for is_pharmacy).", ""]

    # ---------------------------------------------------------------- E01 category sizes
    cat_n = pd.Series(Counter(c for s in v.cats for c in s)).sort_values()
    fig, ax = plt.subplots(figsize=(8, 7))
    colors = [ORANGE if c == "pharmacy" else BLUE for c in cat_n.index]
    ax.barh(cat_n.index, cat_n.values, color=colors, height=0.7)
    for i, n in enumerate(cat_n.values):
        ax.text(n + 4, i, str(n), va="center", fontsize=8, color=INK2)
    ax.set(xlabel="vendors listed in the category",
           title="E01 Vendors per category (pharmacy = classification target)")
    ax.grid(axis="y", visible=False)
    save(fig, "E01_vendors_per_category")
    md += ["## E01 Vendors per category", "",
           f"- {len(v)} vendors, {len(cat_n)} categories, {int(cat_n.sum())} category "
           f"memberships (a vendor can be in several).",
           f"- Largest: {cat_n.index[-1]} {cat_n.iloc[-1]} ({cat_n.iloc[-1] / len(v):.4f} of "
           f"vendors); smallest: {cat_n.index[0]} {cat_n.iloc[0]}.",
           f"- Category sizes differ by a factor of {cat_n.iloc[-1] / cat_n.iloc[0]:.2f}; every "
           f"category is a minority (at most {cat_n.iloc[-1] / len(v):.4f} of vendors), so any "
           "one-vs-rest classifier faces class imbalance.", ""]

    # ---------------------------------------------------------------- E02 n_categories
    nc = v.n_categories.value_counts().sort_index()
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar(nc.index.astype(str), nc.values, color=BLUE, width=0.7)
    ax.set_yscale("log")
    for x, n in zip(nc.index.astype(str), nc.values):
        ax.text(x, n * 1.12, str(n), ha="center", fontsize=8, color=INK2)
    ax.set(xlabel="number of category files the vendor appears in (n_categories)",
           ylabel="vendors (log scale)", title="E02 Most vendors are in exactly one category")
    save(fig, "E02_n_categories")
    md += ["## E02 n_categories", "", md_table(pd.DataFrame(
        {"n_categories": nc.index, "vendors": nc.values,
         "share": (nc.values / len(v)).round(4)})), "",
           f"- {nc.get(1, 0) / len(v):.4f} of vendors are single-category; "
           f"{int((v.n_categories >= 5).sum())} vendors are in 5 or more (large supermarkets / "
           "marketplaces).", ""]

    # ---------------------------------------------------------------- E03 co-occurrence
    cats = sorted(cat_n.index)
    M = pd.DataFrame(0, index=cats, columns=cats)
    for s in v.cats:
        for a in s:
            for b in s:
                if a != b:
                    M.loc[a, b] += 1
    fig, ax = plt.subplots(figsize=(9, 8))
    im = ax.imshow(M.values, cmap="Blues")
    ax.set_xticks(range(len(cats)), cats, rotation=90, fontsize=7)
    ax.set_yticks(range(len(cats)), cats, fontsize=7)
    ax.grid(False)
    fig.colorbar(im, ax=ax, shrink=0.7, label="vendors listed in both categories")
    ax.set_title("E03 Category co-occurrence (off-diagonal)")
    save(fig, "E03_category_cooccurrence")
    pairs = [(a, b, int(M.loc[a, b])) for i, a in enumerate(cats) for b in cats[i + 1:]]
    top = sorted(pairs, key=lambda x: -x[2])[:8]
    md += ["## E03 Category co-occurrence (top pairs)", "",
           md_table(pd.DataFrame(top, columns=["category A", "category B", "vendors in both"])),
           "", "- Overlaps follow real shop types (fruits + vegetables, grocery + kirana), but "
           "some are label noise (kirana + pet_supplies).", ""]

    # ---------------------------------------------------------------- E04 map
    fig, ax = plt.subplots(figsize=(7, 8))
    ph = v.cats.map(lambda s: "pharmacy" in s)
    ax.scatter(v.lon[~ph], v.lat[~ph], s=4, color=LIGHT, label=f"other vendors ({(~ph).sum()})")
    ax.scatter(v.lon[ph], v.lat[ph], s=6, color=BLUE, label=f"pharmacy ({ph.sum()})")
    ax.scatter(reqs.buyer_lon, reqs.buyer_lat, s=60, marker="*", color=ORANGE,
               edgecolor=SURFACE, linewidth=0.8, label=f"requirement buyers ({len(reqs)})")
    ax.set(xlabel="longitude", ylabel="latitude", aspect=1 / np.cos(np.radians(v.lat.mean())),
           title="E04 Vendor locations: South Chennai to Chengalpattu")
    ax.legend(loc="lower right", fontsize=8)
    save(fig, "E04_vendor_map")
    lat_km = (v.lat.max() - v.lat.min()) * KM_PER_DEG_LAT
    mid = (v.lat.max() + v.lat.min()) / 2
    north = float((v.lat > mid).mean())
    lon_km = (v.lon.max() - v.lon.min()) * KM_PER_DEG_LAT * np.cos(np.radians(v.lat.mean()))
    md += ["## E04 Geography", "",
           f"- Bounding box about {lat_km:.1f} km (north-south) × {lon_km:.1f} km (east-west).",
           f"- Density is uneven: {north:.4f} of vendors lie in the northern half of the box "
           f"(latitude > {mid:.4f}, the Chennai side) and {1 - north:.4f} in the southern half "
           "(towards Chengalpattu). See also E12.", ""]

    # ---------------------------------------------------------------- E05 pincodes
    pc = v.pincode.value_counts()
    top20 = pc.head(20)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.bar(top20.index, top20.values, color=BLUE, width=0.7)
    ax.set_xticks(range(len(top20)), top20.index, rotation=60, fontsize=8)
    ax.set(ylabel="vendors", title=f"E05 Top 20 of {len(pc)} pincodes "
           f"({top20.sum() / len(v):.1%} of vendors)")
    save(fig, "E05_top_pincodes")
    md += ["## E05 Pincodes", "",
           f"- {len(pc)} distinct pincodes; the top 20 hold {top20.sum()} vendors "
           f"({top20.sum() / len(v):.4f}). {int((pc < 5).sum())} pincodes have fewer than 5 "
           "vendors.",
           f"- Busiest: {pc.index[0]} ({pc.iloc[0]} vendors). This is why the classifier uses "
           "a top-20 pincode one-hot with 'other' as the reference level.",
           f"- {int(v.pincode_imputed.sum())} vendor had no pincode and got its nearest "
           "neighbour's.", ""]

    # ---------------------------------------------------------------- E06 titles
    ntok = v.title.map(lambda t: len(title_tokens(t)))
    non_latin = v.title.map(lambda t: any(ord(c) > 0x2FF and c.isalpha() for c in t))
    fig, ax = plt.subplots(figsize=(7, 4))
    vc = ntok.value_counts().sort_index()
    ax.bar(vc.index, vc.values, color=BLUE, width=0.75)
    ax.set(xlabel="distinct words in the cleaned title", ylabel="vendors",
           title="E06 Vendor titles are short")
    save(fig, "E06_title_length")
    tok_df = Counter(t for title in v.title for t in title_tokens(title))
    md += ["## E06 Titles", "",
           f"- Median {ntok.median():.0f} words per title (mean {ntok.mean():.2f}, max "
           f"{ntok.max()}). Titles are the only text we have.",
           f"- {int(non_latin.sum())} titles ({non_latin.mean():.4f}) contain non-Latin "
           "letters (mostly Tamil), which is why normalisation is Unicode-aware.",
           f"- {len(tok_df)} distinct words; {sum(n >= 5 for n in tok_df.values())} appear in "
           "at least 5 titles (all vendors; the classifier counts on train only).",
           "- Most common words: " + ", ".join(f"{t} ({n})" for t, n in tok_df.most_common(12))
           + ".", ""]

    # ---------------------------------------------------------------- E07 pharmacy tokens (train)
    train_v, _ = L.split(v.drop(columns=["cats"]))
    pos, neg = train_v[train_v.y == 1], train_v[train_v.y == 0]
    dfp = Counter(t for x in pos.title for t in title_tokens(x))
    dfn = Counter(t for x in neg.title for t in title_tokens(x))
    rows = []
    for t in set(dfp) | set(dfn):
        if dfp[t] + dfn[t] >= 10:
            lo = np.log((dfp[t] + 0.5) / (len(pos) + 1)) - np.log((dfn[t] + 0.5) / (len(neg) + 1))
            rows.append((t, dfp[t], dfn[t], lo))
    tok = pd.DataFrame(rows, columns=["word", "in_pharmacy", "in_other", "log_odds"])
    show = pd.concat([tok.nlargest(10, "log_odds"), tok.nsmallest(10, "log_odds")])
    fig, ax = plt.subplots(figsize=(7.5, 6.5))
    show = show.sort_values("log_odds")
    ax.barh(show.word, show.log_odds,
            color=[BLUE if x > 0 else ORANGE for x in show.log_odds], height=0.7)
    ax.axvline(0, color=MUTED, lw=0.8)
    ax.set(xlabel="smoothed log-odds: pharmacy vs other (train split)",
           title="E07 Title words that separate pharmacies (train)")
    ax.grid(axis="y", visible=False)
    save(fig, "E07_pharmacy_words")
    one_class = int(((tok.in_pharmacy == 0) | (tok.in_other == 0)).sum())
    md += ["## E07 Words vs the pharmacy label (train split, words in ≥ 10 train titles)", "",
           md_table(tok.nlargest(8, "log_odds").round(3)), "",
           md_table(tok.nsmallest(8, "log_odds").round(3)), "",
           f"- Train: {len(train_v)} vendors, {len(pos)} pharmacies "
           f"(prevalence {len(pos) / len(train_v):.4f}).",
           f"- {one_class} of these {len(tok)} frequent words occur in only one class. Words "
           "that appear only in one class are what make the logistic MLE not exist "
           "(separation).", ""]

    # ---------------------------------------------------------------- pairs and target (train)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        ann = lr.load_annotations()
    ann["y"] = ann[lr.TARGET].astype(float)
    train, test = lr.split_by_requirement(ann)

    # E08 distance by stratum
    order = ["near_in_category", "far_in_category", "near_other_category", "random"]
    fig, ax = plt.subplots(figsize=(8, 4))
    data = [ann.loc[ann.stratum == s, "distance_km"].clip(lower=0.01) for s in order]
    ax.boxplot(data, orientation="horizontal", widths=0.5, patch_artist=True,
               boxprops={"facecolor": "#d6e6f8", "edgecolor": BLUE},
               medianprops={"color": ORANGE, "linewidth": 2})
    ax.set_yticks(range(1, 5), order)
    ax.set_xscale("log")
    ax.set(xlabel="distance_km (log scale)", title="E08 Candidate distance by sampling stratum")
    save(fig, "E08_pair_distance_by_stratum")
    strat = ann.groupby("stratum").agg(pairs=("pair_id", "size"),
                                       median_km=("distance_km", "median"),
                                       within_radius=("within_radius", "mean"),
                                       category_match=("category_match", "mean")).reindex(order)
    md += ["## E08 The 450 pairs by sampling stratum (all pairs; no target used)", "",
           md_table(strat.reset_index().round(4)), "",
           f"- Radius limits: {reqs.max_distance_km.value_counts().sort_index().to_dict()} "
           f"(km: requirements). {(reqs.preference_keyword != '').sum()} of 30 requirements "
           "have a preference keyword.",
           f"- keyword_in_title is 1 for only {ann.keyword_in_title.mean():.4f} of pairs "
           f"({int(ann.keyword_in_title.sum())} pairs), so its coefficient is the least "
           "precise.", ""]

    # E09 target distribution (train)
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.hist(train.y, bins=np.arange(-2.5, 103, 5), color=BLUE, edgecolor=SURFACE)
    for a in [0, 25, 50, 75, 100]:
        ax.axvline(a, color=ORANGE, lw=1, ls="--")
    ax.set(xlabel="expected_score (dashed: rubric anchors 0/25/50/75/100)", ylabel="pairs",
           title=f"E09 Target distribution (train, n = {len(train)})")
    save(fig, "E09_target_distribution")
    at_anchor = train.y.isin([0, 25, 50, 75, 100]).mean()
    md += ["## E09 Target distribution (train, 360 pairs)", "",
           f"- Mean {train.y.mean():.2f}, median {train.y.median():.0f}, sd {train.y.std():.2f}, "
           f"min {train.y.min():.0f}, max {train.y.max():.0f}.",
           f"- {at_anchor:.4f} of scores sit exactly on a rubric anchor; the target is "
           "bounded and lumpy, not a smooth Gaussian.",
           f"- {(train.y >= 70).mean():.4f} of train pairs are 'relevant' (≥ 70).", ""]

    # E10 interaction table + E11 correlations
    g = train.groupby(["category_match", "within_radius"]).y.agg(["mean", "size"]).reset_index()
    fig, ax = plt.subplots(figsize=(6.5, 4))
    labels = [f"cat={'Y' if c else 'N'}\nradius={'Y' if w else 'N'}"
              for c, w in zip(g.category_match, g.within_radius)]
    ax.bar(labels, g["mean"], color=[BLUE if c else LIGHT for c in g.category_match], width=0.6)
    for i, (m, n) in enumerate(zip(g["mean"], g["size"])):
        ax.text(i, m + 1.5, f"{m:.1f}\n(n={n})", ha="center", fontsize=8, color=INK2)
    ax.set(ylabel="mean expected_score", ylim=(0, 100),
           title="E10 Category and radius interact (train)")
    save(fig, "E10_category_radius_interaction")
    gm = {(bool(c), bool(w)): m for c, w, m in zip(g.category_match, g.within_radius, g["mean"])}
    radius_gain_cat = gm[(True, True)] - gm[(True, False)]
    radius_gain_nocat = gm[(False, True)] - gm[(False, False)]
    corr = pd.Series({f: np.corrcoef(train[f].astype(float), train.y)[0, 1] for f in FEATURES})
    fig, ax = plt.subplots(figsize=(6.5, 3.8))
    cs = corr.sort_values()
    ax.barh(cs.index, cs.values, color=[BLUE if x > 0 else ORANGE for x in cs.values], height=0.6)
    for i, x in enumerate(cs.values):
        ax.text(x + (0.02 if x >= 0 else -0.02), i, f"{x:.3f}", va="center",
                ha="left" if x >= 0 else "right", fontsize=8, color=INK2)
    ax.axvline(0, color=MUTED, lw=0.8)
    ax.set(xlim=(-0.6, 1.0), xlabel="Pearson correlation with expected_score (train)",
           title="E11 Feature–target correlation")
    ax.grid(axis="y", visible=False)
    save(fig, "E11_feature_target_correlation")
    md += ["## E10 Category × radius (train)", "",
           md_table(g.assign(mean=g["mean"].round(2)).rename(
               columns={"mean": "mean expected_score", "size": "pairs"})), "",
           f"- Being inside the radius adds {radius_gain_cat:.2f} points when the category "
           f"matches but {radius_gain_nocat:.2f} when it does not: the effects are not "
           "additive. A linear (additive) model cannot capture this; kernel ridge can.", "",
           "## E11 Feature–target correlation (train)", "",
           md_table(corr.round(4).rename("pearson_r").rename_axis("feature").reset_index()), "",
           "- category_match dominates; distance is negatively related; is_chain is near 0.",
           ""]

    # E12 nearest-neighbour distance between vendors
    xy = np.c_[v.lat * KM_PER_DEG_LAT, v.lon * KM_PER_DEG_LAT * np.cos(np.radians(v.lat.mean()))]
    d, _ = cKDTree(xy).query(xy, k=2)
    nn = d[:, 1]
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.hist(np.log10(np.clip(nn, 1e-3, None)), bins=40, color=BLUE, edgecolor=SURFACE)
    ax.set_xticks([-3, -2, -1, 0, 1], ["0.001", "0.01", "0.1", "1", "10"])
    ax.set(xlabel="distance to the nearest other vendor (km, log scale)", ylabel="vendors",
           title="E12 Vendor density varies by area")
    save(fig, "E12_nearest_vendor_distance")
    md += ["## E12 Nearest-neighbour distance between vendors", "",
           f"- Median {np.median(nn):.3f} km, 90th percentile {np.quantile(nn, 0.9):.3f} km, "
           f"max {nn.max():.3f} km; {int((nn < 0.01).sum())} vendors are within 10 m of "
           "another (same building / market).",
           "- Half the vendors have a neighbour within this median distance, so in dense areas "
           "many candidates sit at almost the same distance and distance alone cannot rank them; "
           "category and title matter more.", ""]

    (OUT / "eda_numbers.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    print(f"wrote {FIG}/E01-E12 and {OUT / 'eda_numbers.md'}")


if __name__ == "__main__":
    main()
