"""PBL-2 exploratory data analysis for Units III and IV.

Usage: python src/pbl2_eda.py
Reads data/processed/vendors.csv (read-only). Writes ONLY pbl-2/02_eda_insights/figures/E*.png
and pbl-2/02_eda_insights/eda_numbers.md.

Unit III questions: is there cluster structure at all (Hopkins statistic, nearest-neighbour
distances vs complete spatial randomness)? At what scale? Do categories locate together?
Unit IV questions: do addresses have sequential structure (symbol order, first-order
transitions)? How long are the sequences?
The address statistics use the TRAIN split only (the HMM's gold set is in the test split).
"""
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.spatial import ConvexHull, cKDTree

sys.path.insert(0, str(Path(__file__).resolve().parent))
import logistic_regression_classification as L  # noqa: E402
import pbl2_address as AD  # noqa: E402
from matching.features import category_set  # noqa: E402
from pbl2_style import (BLUE, INK2, MUTED, ORANGE, PBL2, SEED, md_table, plt, save,  # noqa: E402
                        to_km)

OUT = PBL2 / "02_eda_insights"
FIG = OUT / "figures"
HOPKINS_M = 300
HOPKINS_REPEATS = 20
CELL_KM = 2.0


def uniform_in(poly, lo, hi, n, rng):
    """n points uniform inside the polygon (rejection sampling from its bounding box)."""
    out = np.empty((0, 2))
    while len(out) < n:
        U = rng.uniform(lo, hi, size=(2 * n, 2))
        out = np.vstack([out, U[poly.contains_points(U)]])
    return out[:n]


def hopkins(X, rng, poly, m=HOPKINS_M):
    """H = sum u / (sum u + sum w): u = NN distance from m uniform points (inside the study
    area's convex hull) to the data, w = NN distance from m sampled data points to the rest.
    H ~ 0.5 for random points, -> 1 for clustered data."""
    tree = cKDTree(X)
    U = uniform_in(poly, X.min(0), X.max(0), m, rng)
    u = tree.query(U, k=1)[0]
    idx = rng.choice(len(X), m, replace=False)
    w = tree.query(X[idx], k=2)[0][:, 1]
    return float(u.sum() / (u.sum() + w.sum()))


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    v = L.load_vendors()
    v["cats"] = v.categories.map(category_set)
    lat0, lon0 = v.lat.mean(), v.lon.mean()
    X = to_km(v.lat, v.lon, lat0, lon0)
    rng = np.random.default_rng(SEED)
    md = ["# PBL-2 EDA numbers (generated by `python src/pbl2_eda.py`; do not edit by hand)", ""]

    # ---------------------------------------------------------------- E01 density
    fig, ax = plt.subplots(figsize=(7, 8))
    hb = ax.hexbin(X[:, 0], X[:, 1], gridsize=45, bins="log", cmap="Blues", mincnt=1)
    fig.colorbar(hb, ax=ax, label="vendors per hexagon (log)")
    ax.set(xlabel="east (km)", ylabel="north (km)", aspect="equal",
           title="E01 Vendor density: dense towns joined by road corridors")
    ax.grid(False)
    save(fig, FIG, "E01_density")
    hull = ConvexHull(X)
    area = hull.volume
    md += ["## E01 Density", "",
           f"- {len(v)} vendors; convex hull area {area:.1f} km², i.e. "
           f"{len(v) / area:.2f} vendors per km² on average.", ""]

    # ---------------------------------------------------------------- E02 NN vs CSR + Hopkins
    tree = cKDTree(X)
    nn = tree.query(X, k=2)[0][:, 1]
    lam = len(X) / area
    csr_mean = 0.5 / np.sqrt(lam)                   # Clark-Evans expectation under CSR
    R_ce = nn.mean() / csr_mean
    from matplotlib.path import Path as MPath
    poly = MPath(X[hull.vertices])
    H = [hopkins(X, rng, poly) for _ in range(HOPKINS_REPEATS)]
    # the same number of uniform points inside the hull: complete spatial randomness (CSR)
    U = uniform_in(poly, X.min(0), X.max(0), len(X), rng)
    nn_csr = cKDTree(U).query(U, k=2)[0][:, 1]
    H_csr = [hopkins(U, rng, poly) for _ in range(HOPKINS_REPEATS)]
    fig, ax = plt.subplots(figsize=(8, 4.5))
    bins = np.logspace(-3, 1, 50)
    ax.hist(nn, bins=bins, color=BLUE, alpha=0.8, label="vendors")
    ax.hist(nn_csr, bins=bins, histtype="step", color=ORANGE, lw=2,
            label="same number of uniform random points")
    ax.set_xscale("log")
    ax.set(xlabel="distance to nearest other vendor (km, log)", ylabel="vendors",
           title="E02 Vendors are far closer together than random points")
    ax.legend(fontsize=8)
    save(fig, FIG, "E02_nearest_neighbour_vs_random")
    md += ["## E02 Clustering tendency", "",
           md_table(pd.DataFrame({
               "statistic": ["median NN distance (m)", "mean NN distance (m)",
                             "Clark-Evans R = mean NN / CSR expectation",
                             f"Hopkins H (mean of {HOPKINS_REPEATS}, m = {HOPKINS_M})",
                             "share of vendors with another vendor within 50 m"],
               "vendors": [f"{np.median(nn) * 1000:.1f}", f"{nn.mean() * 1000:.1f}",
                           f"{R_ce:.4f}", f"{np.mean(H):.4f} (sd {np.std(H):.4f})",
                           f"{(nn < 0.05).mean():.4f}"],
               "uniform random points": [f"{np.median(nn_csr) * 1000:.1f}",
                                         f"{nn_csr.mean() * 1000:.1f}",
                                         f"{nn_csr.mean() / csr_mean:.4f}",
                                         f"{np.mean(H_csr):.4f}",
                                         f"{(nn_csr < 0.05).mean():.4f}"]})), "",
           "- R < 1 and H near 1 mean strong clustering, so clustering is meaningful here.",
           f"- {int((nn == 0).sum())} vendors share exact coordinates with another vendor "
           "(same building / mall).", ""]

    # ---------------------------------------------------------------- E03 multi-scale
    radii = [0.1, 0.25, 0.5, 1, 2, 5]
    within = [np.mean([len(x) - 1 for x in tree.query_ball_point(X, r)]) for r in radii]
    within_csr = [lam * np.pi * r ** 2 for r in radii]
    fig, ax = plt.subplots(figsize=(7, 4.5))
    ax.loglog(radii, within, "o-", color=BLUE, label="vendors (observed)")
    ax.loglog(radii, within_csr, "s--", color=ORANGE, label="random (λπr²)")
    ax.set(xlabel="radius r (km)", ylabel="mean other vendors within r",
           title="E03 Clustering at every scale")
    ax.legend(fontsize=8)
    save(fig, FIG, "E03_neighbours_by_radius")
    md += ["## E03 Neighbours within r", "",
           md_table(pd.DataFrame({"r (km)": radii, "observed": [f"{x:.2f}" for x in within],
                                  "random": [f"{x:.3f}" for x in within_csr],
                                  "ratio": [f"{a / b:.1f}" for a, b in zip(within,
                                                                          within_csr)]})), "",
           "- The excess over random is largest at small r and never disappears: clusters "
           "exist at street, neighbourhood and town scale. Expect BIC to keep adding "
           "components.", ""]

    # ---------------------------------------------------------------- E04 category co-location
    cats = sorted({c for s in v.cats for c in s})
    cell = np.floor(X / CELL_KM).astype(int)
    key = pd.Series([f"{a}_{b}" for a, b in cell])
    C = pd.DataFrame(0, index=sorted(set(key)), columns=cats)
    for k, s in zip(key, v.cats):
        for c in s:
            C.loc[k, c] += 1
    corr = np.log1p(C).corr().values
    fig, ax = plt.subplots(figsize=(9, 8))
    im = ax.imshow(corr, cmap="RdBu_r", vmin=-1, vmax=1)
    ax.set_xticks(range(len(cats)), cats, rotation=90, fontsize=7)
    ax.set_yticks(range(len(cats)), cats, fontsize=7)
    ax.grid(False)
    fig.colorbar(im, ax=ax, shrink=0.7, label=f"correlation of log(1+count) over {len(C)} cells")
    ax.set_title(f"E04 Which categories locate together ({CELL_KM:.0f} km cells)")
    save(fig, FIG, "E04_category_colocation")
    off = [(cats[i], cats[j], corr[i, j]) for i in range(len(cats)) for j in range(i + 1, len(cats))]
    off.sort(key=lambda t: -t[2])
    md += ["## E04 Category co-location", "",
           f"- {len(C)} non-empty {CELL_KM:.0f} km cells. Mean off-diagonal correlation "
           f"{np.mean([t[2] for t in off]):.4f} (all positive = busy cells have more of "
           "everything; this size effect is why the PCA in section 3 uses shares, not counts).",
           "", md_table(pd.DataFrame([(a, b, f"{c:.3f}") for a, b, c in off[:6]],
                                     columns=["category A", "category B", "corr"])), "",
           "Weakest pairs:", "",
           md_table(pd.DataFrame([(a, b, f"{c:.3f}") for a, b, c in off[-4:]],
                                 columns=["category A", "category B", "corr"])), ""]

    # ---------------------------------------------------------------- addresses (train only)
    train, _ = L.split(v)
    train = train[train.address.map(lambda a: len(AD.segments(a)) > 0)]
    towns = AD.town_gazetteer(train.address)
    seqs = [AD.encode(a, towns) for a in train.address]
    lens = np.array([len(s) for s in seqs])
    fig, ax = plt.subplots(figsize=(7, 4))
    lc = pd.Series(lens).value_counts().sort_index()
    ax.bar(lc.index, lc.values, color=BLUE)
    ax.set(xlabel="parts per address (comma-separated)", ylabel="train addresses",
           title="E05 Address sequence lengths")
    save(fig, FIG, "E05_address_lengths")
    md += ["## E05 Address sequences (train split)", "",
           f"- {len(seqs)} addresses, {lens.sum()} parts; length median {np.median(lens):.0f}, "
           f"mean {lens.mean():.2f}, min {lens.min()}, max {lens.max()}.",
           f"- {np.mean([s[-1] == AD.O['STATEPIN'] for s in seqs]):.4f} end with the "
           "'Tamil Nadu <pincode>' part.", ""]

    # symbol frequency by position from the end
    P = np.zeros((len(AD.SYMBOLS), 6))
    for s in seqs:
        for back in range(min(6, len(s))):
            P[s[-1 - back], back] += 1
    P = P / P.sum(0, keepdims=True)
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.imshow(P, cmap="Blues", vmin=0, vmax=1, aspect="auto")
    ax.set_yticks(range(len(AD.SYMBOLS)), AD.SYMBOLS, fontsize=8)
    ax.set_xticks(range(6), ["last", "2nd last", "3rd last", "4th last", "5th last",
                             "6th last"], fontsize=8)
    for i in range(P.shape[0]):
        for j in range(P.shape[1]):
            ax.text(j, i, f"{P[i, j]:.2f}", ha="center", va="center", fontsize=7,
                    color="white" if P[i, j] > 0.55 else INK2)
    ax.grid(False)
    ax.set_title("E06 What kind of part appears at each position (from the end)")
    save(fig, FIG, "E06_symbol_by_position")
    freq = Counter(np.concatenate(seqs))
    md += ["## E06 Symbols and position", "",
           md_table(pd.DataFrame({"symbol": AD.SYMBOLS,
                                  "count": [freq.get(i, 0) for i in range(len(AD.SYMBOLS))],
                                  "share": [f"{freq.get(i, 0) / lens.sum():.4f}"
                                            for i in range(len(AD.SYMBOLS))],
                                  "share at last position": [f"{P[i, 0]:.3f}"
                                                             for i in range(len(AD.SYMBOLS))],
                                  "share at 2nd last": [f"{P[i, 1]:.3f}"
                                                        for i in range(len(AD.SYMBOLS))]})), "",
           "- The role of a part depends strongly on where it sits: order matters, so a "
           "sequence model is appropriate.", ""]

    # first-order transitions between symbols
    T = np.zeros((len(AD.SYMBOLS),) * 2)
    for s in seqs:
        np.add.at(T, (s[:-1], s[1:]), 1)
    Tn = T / np.maximum(T.sum(1, keepdims=True), 1)
    fig, ax = plt.subplots(figsize=(8, 6.5))
    ax.imshow(Tn, cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks(range(len(AD.SYMBOLS)), AD.SYMBOLS, rotation=45, ha="right", fontsize=8)
    ax.set_yticks(range(len(AD.SYMBOLS)), AD.SYMBOLS, fontsize=8)
    for i in range(Tn.shape[0]):
        for j in range(Tn.shape[1]):
            ax.text(j, i, f"{Tn[i, j]:.2f}", ha="center", va="center", fontsize=6.5,
                    color="white" if Tn[i, j] > 0.55 else INK2)
    ax.set(xlabel="next part", ylabel="current part",
           title="E07 First-order transitions p(next symbol | symbol)")
    ax.grid(False)
    save(fig, FIG, "E07_symbol_transitions")
    marg = np.array([freq.get(i, 0) for i in range(len(AD.SYMBOLS))]) / lens.sum()
    H0 = float(-(marg[marg > 0] * np.log2(marg[marg > 0])).sum())
    rowp = T.sum(1) / T.sum()
    with np.errstate(divide="ignore", invalid="ignore"):
        H1 = float(-np.nansum(rowp[:, None] * Tn * np.where(Tn > 0, np.log2(Tn), 0)))
    md += ["## E07 First-order structure", "",
           f"- Entropy of a part's symbol ignoring context: {H0:.3f} bits; given the previous "
           f"part's symbol: {H1:.3f} bits ({1 - H1 / H0:.4f} reduction). Knowing the previous "
           "part removes a large share of the uncertainty: a first-order Markov assumption "
           "captures real structure.",
           f"- p(STATEPIN → anything) row sum is "
           f"{T[AD.O['STATEPIN']].sum() / max(freq[AD.O['STATEPIN']], 1):.4f}: the state part is "
           "almost always last.", ""]

    (OUT / "eda_numbers.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"Hopkins {np.mean(H):.4f} vs random {np.mean(H_csr):.4f}; Clark-Evans R {R_ce:.4f}; "
          f"H0 {H0:.3f} H1 {H1:.3f}")
    print(f"wrote {OUT / 'eda_numbers.md'} and figures E01-E07")


if __name__ == "__main__":
    main()
